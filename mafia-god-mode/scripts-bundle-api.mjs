// Bundles functions/room.ts into one dependency-free CommonJS file at api/room.js.
// Vercel runs api/room.js as-is, so it cannot trip over TypeScript or module-format settings.
import { build } from "esbuild";

await build({
  entryPoints: ["functions/room.ts"],
  outfile: "api/room.js",
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  legalComments: "none",
  footer: { js: "module.exports = module.exports.default;" },
  banner: { js: "// GENERATED by `npm run build:api` from functions/room.ts. Do not edit." },
});
console.log("api/room.js written");
