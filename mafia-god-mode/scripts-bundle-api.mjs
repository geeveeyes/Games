// Bundles each functions/*.ts into one dependency-free CommonJS file under api/.
// Vercel runs api/room.js as-is, so it cannot trip over TypeScript or module-format settings.
import { build } from "esbuild";

await build({
  entryPoints: ["functions/room.ts", "functions/feedback.ts"],
  outdir: "api",
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  legalComments: "none",
  footer: { js: "module.exports = module.exports.default;" },
  banner: { js: "// GENERATED by `npm run build:api` from functions/room.ts. Do not edit." },
});
console.log("api/room.js and api/feedback.js written");
